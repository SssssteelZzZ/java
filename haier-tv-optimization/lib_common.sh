#!/usr/bin/env bash
# =============================================================================
#  lib_common.sh — общие функции для всех скриптов набора
# =============================================================================
#  Этот файл не запускается сам по себе, его подключают через `source`.
#  Здесь лежит то, что нужно каждому скрипту: поиск телевизора, обёртка над adb,
#  проверка «защищённости» пакета и цветной вывод.
# =============================================================================

# --- Цвета для вывода (чтобы важное было видно сразу) ------------------------
# $'\e[..m' — ANSI-коды. Если терминал их не понимает, просто будет текст.
C_RED=$'\e[31m'; C_GRN=$'\e[32m'; C_YEL=$'\e[33m'; C_BLU=$'\e[36m'; C_OFF=$'\e[0m'

# --- Куда складывать отчёты и резервные копии --------------------------------
# Все логи пишем рядом со скриптами, в папку reports/ — потом по ним делаем откат.
SCRIPT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
REPORT_DIR="${SCRIPT_DIR}/reports"
mkdir -p "${REPORT_DIR}"

# -----------------------------------------------------------------------------
#  tv_find — определить адрес телевизора
# -----------------------------------------------------------------------------
#  Логика: если адрес передали переменной окружения TV_ADDR — берём её.
#  Иначе ищем в `adb devices` первое устройство в состоянии "device",
#  адрес которого выглядит как IP:порт (то есть подключено по сети, а не USB).
tv_find() {
  if [ -n "${TV_ADDR:-}" ]; then
    echo "${TV_ADDR}"; return 0
  fi
  # awk: берём строки со статусом device, первый столбец = адрес.
  local found
  found="$(adb devices | awk '$2=="device" && $1 ~ /^[0-9]+\.[0-9]+\.[0-9]+\.[0-9]+:[0-9]+$/ {print $1; exit}')"
  if [ -z "${found}" ]; then
    echo "${C_RED}[!] Телевизор не подключён. Сначала запусти ./01_connect_tv.sh${C_OFF}" >&2
    return 1
  fi
  echo "${found}"
}

# -----------------------------------------------------------------------------
#  tv_sh — выполнить команду в shell телевизора
# -----------------------------------------------------------------------------
#  Обёртка, чтобы не писать каждый раз `adb -s адрес shell ...`.
#  tr -d '\r' убирает возврат каретки: Android отдаёт CRLF, из-за него ломаются
#  сравнения строк и списки пакетов «склеиваются» с мусором.
tv_sh() {
  adb -s "${DEV}" shell "$@" 2>/dev/null | tr -d '\r'
}

# -----------------------------------------------------------------------------
#  is_protected — проверить, входит ли пакет в «белый список»
# -----------------------------------------------------------------------------
#  Возвращает 0 (истина в bash), если пакет трогать нельзя.
#  Сравнение по префиксу: "com.android.providers" защищает всё семейство
#  com.android.providers.* — так один пункт закрывает десяток системных пакетов.
is_protected() {
  local pkg="$1" prot
  for prot in "${PROTECTED_PACKAGES[@]}"; do
    case "${pkg}" in
      "${prot}"|"${prot}".*) return 0 ;;   # точное совпадение или пакет-потомок
    esac
  done
  return 1
}

# -----------------------------------------------------------------------------
#  pkg_installed — установлен ли пакет и активен ли он для пользователя 0
# -----------------------------------------------------------------------------
#  `pm list packages` без флагов показывает только ВКЛЮЧЁННЫЕ пакеты.
#  Точное совпадение через grep -x, иначе "ru.ivi.client" совпадёт
#  и с "ru.ivi.client.pro", и мы удалим не то.
pkg_installed() {
  tv_sh "pm list packages" | sed 's/^package://' | grep -qx "$1"
}

# -----------------------------------------------------------------------------
#  free_ram_mb — сколько сейчас свободной оперативной памяти (МБ)
# -----------------------------------------------------------------------------
#  Читаем MemAvailable из /proc/meminfo (значение в килобайтах) и делим на 1024.
#  Нужно, чтобы показать эффект «до / после» в цифрах, а не на глаз.
free_ram_mb() {
  tv_sh "cat /proc/meminfo" | awk '/MemAvailable/ {printf "%d", $2/1024}'
}
