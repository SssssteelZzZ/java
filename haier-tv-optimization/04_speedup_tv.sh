#!/usr/bin/env bash
# =============================================================================
#  04_speedup_tv.sh — ускорение интерфейса + блокировка рекламы на уровне сети
# =============================================================================
#  ЧТО ДЕЛАЕТ И ПОЧЕМУ ЭТО РАБОТАЕТ:
#
#  1. АНИМАЦИИ. Android рисует переходы между экранами по 300-400 мс.
#     Это не «тормоза», это заложенная задержка. Ускорив их в 2 раза (или убрав),
#     получаешь самый заметный на глаз прирост отзывчивости — интерфейс
#     начинает реагировать на пульт мгновенно.
#
#  2. PRIVATE DNS (главный анти-рекламный приём). Телевизор направляется на
#     DNS-сервер с фильтром рекламы. Домены рекламных сетей просто не
#     резолвятся — баннеры не грузятся НИ В ОДНОМ приложении, включая те,
#     которые нельзя удалить. Работает на уровне системы, root не нужен.
#
#  3. ФОНОВЫЕ СКАНЫ. Wi-Fi и Bluetooth по умолчанию сканируют эфир постоянно,
#     даже когда выключены. Для телевизора, который стоит на месте
#     и подключён к одной сети, это чистая трата CPU.
#
#  4. ЗАМОРОЗКА КЭШИРОВАННЫХ ПРИЛОЖЕНИЙ (Android 11+). Приложения, которые
#     висят в памяти «про запас», перестают получать процессорное время.
#
#  ФЛАГИ:
#    --no-anim        полностью отключить анимации (0x вместо 0.5x)
#    --dns=ХОСТ       свой DNS вместо AdGuard (например --dns=security.cloudflare-dns.com)
#    --no-dns         не трогать DNS вообще
#    --aggressive     жёсткие твики: меньше фоновых процессов, отключение
#                     постоянной проверки подключения к интернету
#    --compile        AOT-перекомпиляция всех приложений (ускоряет запуск,
#                     занимает 5-20 минут, телевизор в это время будет тормозить)
#
#  ОТКАТ: старые значения сохраняются в reports/settings-backup-*.txt,
#         вернуть всё можно скриптом 99_restore_tv.sh.
# =============================================================================

set -u
cd "$(dirname "$0")"
source ./lib_common.sh

# --- Значения по умолчанию и разбор аргументов -------------------------------
ANIM="0.5"                              # 0.5 = вдвое быстрее стандартных анимаций
DNS_HOST="dns.adguard-dns.com"          # AdGuard DNS: режет рекламу и трекеры
USE_DNS=1; AGGRESSIVE=0; DO_COMPILE=0
for arg in "$@"; do
  case "${arg}" in
    --no-anim)    ANIM="0" ;;
    --no-dns)     USE_DNS=0 ;;
    --dns=*)      DNS_HOST="${arg#--dns=}" ;;
    --aggressive) AGGRESSIVE=1 ;;
    --compile)    DO_COMPILE=1 ;;
    *) echo "${C_RED}Неизвестный флаг: ${arg}${C_OFF}"; exit 1 ;;
  esac
done

DEV="$(tv_find)" || exit 1
STAMP="$(date +%Y%m%d-%H%M%S)"
BACKUP="${REPORT_DIR}/settings-backup-${STAMP}.txt"
: > "${BACKUP}"

# -----------------------------------------------------------------------------
#  set_setting — записать настройку, предварительно сохранив старое значение
# -----------------------------------------------------------------------------
#  $1 = раздел (global/secure/system), $2 = ключ, $3 = новое значение
#  Старое значение уходит в файл бэкапа в формате "раздел ключ значение",
#  чтобы скрипт отката смог построить обратную команду построчно.
set_setting() {
  local ns="$1" key="$2" val="$3" old
  old="$(tv_sh "settings get ${ns} ${key}")"
  printf '%s %s %s\n' "${ns}" "${key}" "${old:-null}" >> "${BACKUP}"
  tv_sh "settings put ${ns} ${key} ${val}" >/dev/null
  printf '  %-38s %-12s → %s\n' "${key}" "${old:-—}" "${val}"
}

echo "${C_BLU}=== Оптимизация ${DEV} ===${C_OFF}"
RAM_BEFORE="$(free_ram_mb)"

# --- 1. Анимации --------------------------------------------------------------
echo
echo "${C_YEL}[1] Скорость анимаций (главный прирост отзывчивости)${C_OFF}"
set_setting global window_animation_scale     "${ANIM}"   # анимация открытия окон
set_setting global transition_animation_scale "${ANIM}"   # переходы между экранами
set_setting global animator_duration_scale    "${ANIM}"   # анимации внутри приложений

# --- 2. DNS с фильтром рекламы -----------------------------------------------
if [ "${USE_DNS}" = "1" ]; then
  echo
  echo "${C_YEL}[2] Блокировка рекламы через Private DNS (${DNS_HOST})${C_OFF}"
  # hostname = режим DNS-over-TLS по имени хоста; трафик к DNS ещё и шифруется
  set_setting global private_dns_mode      "hostname"
  set_setting global private_dns_specifier "${DNS_HOST}"
else
  echo
  echo "${C_YEL}[2] DNS пропущен (--no-dns)${C_OFF}"
fi

# --- 3. Отключение рекламного профиля и отчётов ------------------------------
echo
echo "${C_YEL}[3] Реклама и телеметрия${C_OFF}"
set_setting secure limit_ad_tracking          "1"   # запрет таргетинга по рекламному ID
set_setting secure send_action_app_error      "0"   # не слать отчёты о падениях
set_setting global network_recommendations_enabled "0"  # не опрашивать «рекомендованные сети»

# --- 4. Фоновые сканы эфира ---------------------------------------------------
echo
echo "${C_YEL}[4] Фоновые сканирования (телевизор стоит на месте — они не нужны)${C_OFF}"
set_setting global wifi_scan_always_enabled "0"   # постоянный поиск сетей Wi-Fi
set_setting global ble_scan_always_enabled  "0"   # постоянный поиск Bluetooth-устройств

# --- 5. Заморозка кэшированных приложений (Android 11+) ----------------------
echo
echo "${C_YEL}[5] Заморозка фоновых приложений${C_OFF}"
# Если система старше 11, ключа нет — команда просто ничего не сделает, это безопасно.
set_setting global cached_apps_freezer "enabled"

# --- 6. Жёсткие твики (только по флагу) --------------------------------------
if [ "${AGGRESSIVE}" = "1" ]; then
  echo
  echo "${C_YEL}[6] Жёсткий режим${C_OFF}"
  # Ограничиваем количество процессов, которые система держит «про запас».
  # На телевизорах с 1.5-2 ГБ ОЗУ это убирает свопинг и подтормаживания,
  # платой будет чуть более долгое переключение между приложениями.
  set_setting global activity_manager_constants "max_cached_processes=8"
  # Отключаем постоянные обращения к серверам Google для проверки интернета
  # (каждые несколько секунд уходит запрос connectivitycheck.gstatic.com).
  set_setting global captive_portal_mode "0"
else
  echo
  echo "${C_BLU}[6] Жёсткий режим пропущен (включается флагом --aggressive)${C_OFF}"
fi

# --- 7. AOT-перекомпиляция приложений (только по флагу) ----------------------
if [ "${DO_COMPILE}" = "1" ]; then
  echo
  echo "${C_YEL}[7] Перекомпиляция приложений в машинный код (это надолго)${C_OFF}"
  echo "    Не выключай телевизор. Приложения после этого стартуют заметно быстрее."
  # -m speed = максимальная оптимизация вместо профильной, -a = все пакеты
  adb -s "${DEV}" shell "cmd package compile -m speed -a" 2>&1 | tail -5
fi

sleep 3
RAM_AFTER="$(free_ram_mb)"

echo
echo "${C_GRN}=== ГОТОВО ===${C_OFF}"
echo "  Свободная ОЗУ : ${RAM_BEFORE} МБ → ${RAM_AFTER} МБ"
echo "  Бэкап настроек: ${BACKUP}"
echo
echo "Рекомендуется перезагрузить телевизор, чтобы всё применилось:"
echo "  adb -s ${DEV} reboot"
