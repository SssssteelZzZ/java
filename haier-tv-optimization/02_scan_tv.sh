#!/usr/bin/env bash
# =============================================================================
#  02_scan_tv.sh — инвентаризация телевизора БЕЗ каких-либо изменений
# =============================================================================
#  ЗАЧЕМ: прежде чем что-то удалять, надо увидеть, что вообще стоит.
#  Скрипт ничего не меняет — только читает и пишет отчёты в reports/.
#
#  ЧТО ДЕЛАЕТ:
#   1. сохраняет полный список пакетов (пригодится для отката);
#   2. раскладывает их по группам: мусор / Google / реклама по шаблону / прочее;
#   3. показывает топ приложений по расходу оперативной памяти прямо сейчас;
#   4. пишет базовые цифры (свободная ОЗУ), чтобы потом сравнить «до/после».
# =============================================================================

set -u
cd "$(dirname "$0")"                 # работаем от папки скрипта, а не откуда запустили
source ./lib_common.sh               # общие функции (tv_sh, is_protected, цвета)
source ./tv_packages.conf            # списки пакетов

DEV="$(tv_find)" || exit 1           # адрес телевизора; при ошибке выходим
STAMP="$(date +%Y%m%d-%H%M%S)"       # метка времени для имён файлов отчётов

echo "${C_BLU}=== Сканирование ${DEV} ===${C_OFF}"
echo "  Модель : $(tv_sh getprop ro.product.model)"
echo "  Android: $(tv_sh getprop ro.build.version.release)"
echo "  ОЗУ свободно сейчас: $(free_ram_mb) МБ"
echo

# --- 1. Полный список установленных пакетов ---------------------------------
# Он же — «снимок системы». Если что-то пойдёт не так, по нему восстановимся.
ALL="${REPORT_DIR}/packages-all-${STAMP}.txt"
tv_sh "pm list packages" | sed 's/^package://' | sort > "${ALL}"
echo "Всего активных пакетов: $(wc -l < "${ALL}")  → ${ALL}"

# Отдельно сохраняем уже отключённые/удалённые ранее — чтобы видеть картину целиком.
tv_sh "pm list packages -u" | sed 's/^package://' | sort > "${REPORT_DIR}/packages-including-removed-${STAMP}.txt"

# --- 2. Группировка: что из известного мусора реально стоит ------------------
FOUND_SAFE=()
for p in "${BLOAT_SAFE[@]}"; do
  # grep -qx = точное совпадение строки целиком (защита от ложных срабатываний)
  grep -qx "${p}" "${ALL}" && FOUND_SAFE+=("${p}")
done

FOUND_GOOGLE=()
for entry in "${BLOAT_GOOGLE[@]}"; do
  p="${entry%%|*}"                   # отрезаем описание после символа |
  grep -qx "${p}" "${ALL}" && FOUND_GOOGLE+=("${entry}")
done

# --- 3. Автопоиск рекламы/телеметрии по шаблонам -----------------------------
# Здесь ловим то, что нельзя знать заранее: у каждой прошивки свои модули.
# Найденное в защищённом списке сразу отбрасываем, чтобы не пугать зря.
FOUND_PATTERN=()
for pat in "${BLOAT_PATTERNS[@]}"; do
  while IFS= read -r p; do
    [ -z "${p}" ] && continue
    is_protected "${p}" && continue
    # проверяем, что пакет ещё не попал в список выше (без дублей)
    printf '%s\n' "${FOUND_PATTERN[@]:-}" | grep -qx "${p}" && continue
    FOUND_PATTERN+=("${p}")
  done < <(grep -E "${pat}" "${ALL}" || true)
done

# --- 4. Вывод результата ------------------------------------------------------
echo
echo "${C_YEL}--- Найденный предустановленный мусор (${#FOUND_SAFE[@]} шт., удаляется скриптом 03) ---${C_OFF}"
printf '  %s\n' "${FOUND_SAFE[@]:-(ничего не найдено)}"

echo
echo "${C_YEL}--- Сервисы Google (${#FOUND_GOOGLE[@]} шт., только с флагом --google) ---${C_OFF}"
for entry in "${FOUND_GOOGLE[@]:-}"; do
  [ -z "${entry}" ] && continue
  printf '  %-45s %s\n' "${entry%%|*}" "${entry#*|}"
done

echo
echo "${C_YEL}--- Подозрение на рекламу/телеметрию по шаблонам (${#FOUND_PATTERN[@]} шт.) ---${C_OFF}"
echo "    Проверь глазами: сюда может попасть что-то нужное именно тебе."
printf '  %s\n' "${FOUND_PATTERN[@]:-(ничего не найдено)}"

# --- 5. Кто прямо сейчас ест память ------------------------------------------
# dumpsys meminfo отдаёт таблицу процессов, отсортированную по расходу.
# Берём первые 15 строк с числами — это и есть главные «пожиратели».
echo
echo "${C_YEL}--- ТОП-15 процессов по расходу ОЗУ прямо сейчас ---${C_OFF}"
# sed '1d;$d' убирает первую строку (заголовок) и последнюю (маркер следующей секции)
tv_sh "dumpsys meminfo" | sed -n '/Total PSS by process/,/Total PSS by OOM/p' | sed '1d;$d' | head -15

# --- 6. Сохраняем сводку в файл ----------------------------------------------
SUMMARY="${REPORT_DIR}/scan-summary-${STAMP}.txt"
{
  echo "Дата сканирования : $(date)"
  echo "Устройство        : ${DEV} / $(tv_sh getprop ro.product.model)"
  echo "Android           : $(tv_sh getprop ro.build.version.release)"
  echo "Свободно ОЗУ, МБ  : $(free_ram_mb)"
  echo "Всего пакетов     : $(wc -l < "${ALL}")"
  echo
  echo "[МУСОР]";      printf '%s\n' "${FOUND_SAFE[@]:-}"
  echo; echo "[GOOGLE]"; printf '%s\n' "${FOUND_GOOGLE[@]:-}"
  echo; echo "[ПО ШАБЛОНАМ]"; printf '%s\n' "${FOUND_PATTERN[@]:-}"
} > "${SUMMARY}"

echo
echo "${C_GRN}Сводка сохранена: ${SUMMARY}${C_OFF}"
echo "Дальше: ./03_debloat_tv.sh --dry-run   (посмотреть план без изменений)"
