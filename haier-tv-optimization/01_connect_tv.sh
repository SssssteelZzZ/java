#!/usr/bin/env bash
# =============================================================================
#  01_connect_tv.sh — подключение к телевизору по Wi-Fi (ADB over Wi-Fi)
# =============================================================================
#  ЗАЧЕМ: все остальные скрипты работают через adb. Этот — устанавливает связь.
#
#  ВАЖНО ПРО ANDROID 11+ (а на Haier Android TV PRO именно он):
#  беспроводная отладка требует ДВА шага и ДВА РАЗНЫХ ПОРТА:
#    Шаг 1 — СОПРЯЖЕНИЕ (один раз): порт и 6-значный код появляются на ТВ
#            в пункте «Подключить устройство с помощью кода подключения».
#            Порт там КАЖДЫЙ РАЗ НОВЫЙ и живёт, пока открыто окно с кодом.
#    Шаг 2 — ПОДКЛЮЧЕНИЕ: порт с главного экрана отладки (у тебя 37765).
#  Перепутать их — самая частая ошибка, adb выдаст «failed to connect».
#
#  ЗАПУСК:
#     ./01_connect_tv.sh                 # взять IP:порт из настроек ниже
#     ./01_connect_tv.sh 192.168.0.149 37765
# =============================================================================

set -u  # обращение к необъявленной переменной = ошибка, а не пустая строка

# --- Настройки по умолчанию (взяты с экрана телевизора) ----------------------
TV_IP="${1:-192.168.0.149}"      # IP телевизора в домашней сети
TV_PORT="${2:-37765}"            # порт ПОДКЛЮЧЕНИЯ (не сопряжения!)
TV_ADDR="${TV_IP}:${TV_PORT}"

# --- Проверка, что adb вообще установлен -------------------------------------
# command -v возвращает путь к программе; если пусто — её нет в системе.
if ! command -v adb >/dev/null 2>&1; then
  cat <<'HELP'
[!] adb не найден. Установи Android Platform Tools:

  Windows : скачать https://dl.google.com/android/repository/platform-tools-latest-windows.zip
            распаковать, запускать скрипты из этой папки (Git Bash) или использовать .bat
  macOS   : brew install --cask android-platform-tools
  Ubuntu  : sudo apt install adb
  Arch    : sudo pacman -S android-tools
HELP
  exit 1
fi

echo "=== Подключение к телевизору ${TV_ADDR} ==="

# --- Шаг 0: поднимаем adb-сервер и чистим старые «мёртвые» подключения -------
# Без этого adb иногда держит зависшую сессию с прошлого раза и молча падает.
adb start-server >/dev/null 2>&1
adb disconnect "${TV_ADDR}" >/dev/null 2>&1

# --- Шаг 1: пробуем подключиться сразу (если сопряжение уже было) ------------
echo "[1/3] Пробую подключиться напрямую..."
adb connect "${TV_ADDR}" >/dev/null 2>&1
sleep 1

# adb devices выводит список; grep ищет наш адрес со статусом device (готов).
# Статус offline/unauthorized означает, что связи по факту нет.
if adb devices | grep -q "^${TV_ADDR}[[:space:]]*device$"; then
  echo "[OK] Уже сопряжён — подключение установлено."
else
  # --- Шаг 2: нужно сопряжение по коду ---------------------------------------
  echo "[2/3] Нужно сопряжение (первый запуск)."
  echo
  echo "  На телевизоре: Настройки → Для разработчиков → Отладка по Wi-Fi"
  echo "                 → «Подключить устройство с помощью кода подключения»"
  echo "  На экране появятся: 6-значный КОД и адрес вида ${TV_IP}:XXXXX"
  echo "  ВНИМАНИЕ: порт сопряжения ДРУГОЙ, не ${TV_PORT}. Не закрывай это окно!"
  echo
  read -r -p "  Введи ПОРТ СОПРЯЖЕНИЯ (5 цифр с экрана ТВ): " PAIR_PORT
  read -r -p "  Введи КОД сопряжения (6 цифр): " PAIR_CODE

  # adb pair принимает код как второй аргумент — без интерактивного запроса.
  if ! adb pair "${TV_IP}:${PAIR_PORT}" "${PAIR_CODE}"; then
    echo "[!] Сопряжение не удалось. Причины по частоте:"
    echo "    - компьютер и ТВ в разных сетях (например, ПК по кабелю, ТВ по Wi-Fi гостевой)"
    echo "    - окно с кодом на ТВ закрылось (порт и код меняются каждый раз)"
    echo "    - в роутере включена изоляция клиентов (AP isolation) — отключить в настройках Wi-Fi"
    exit 1
  fi

  echo "[3/3] Сопряжение прошло, подключаюсь к ${TV_ADDR}..."
  adb connect "${TV_ADDR}"
  sleep 1
fi

# --- Финальная проверка: реально ли устройство отвечает ----------------------
# Спрашиваем модель — если ответ пришёл, канал рабочий, а не просто «connected».
MODEL="$(adb -s "${TV_ADDR}" shell getprop ro.product.model 2>/dev/null | tr -d '\r')"
if [ -z "${MODEL}" ]; then
  echo "[!] Устройство не отвечает. Проверь, что на ТВ не появилось окно"
  echo "    «Разрешить отладку?» — его нужно подтвердить пультом."
  exit 1
fi

ANDROID_VER="$(adb -s "${TV_ADDR}" shell getprop ro.build.version.release | tr -d '\r')"
echo
echo "=== ПОДКЛЮЧЕНО ==="
echo "  Модель      : ${MODEL}"
echo "  Android     : ${ANDROID_VER}"
echo "  Адрес       : ${TV_ADDR}"
echo
echo "Дальше: ./02_scan_tv.sh   (посмотреть, что вообще стоит на телевизоре)"
